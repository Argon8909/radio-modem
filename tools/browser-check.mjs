// Optional integration check. Playwright is a test tool, not an app dependency.
import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { encodePacket } from '../src/packet.js';
import { modulate } from '../src/modem.js';
const { chromium } = await import(process.env.RB_PLAYWRIGHT_MODULE || 'playwright');
const temp = await mkdtemp(join(tmpdir(), 'radiobridge-browser-'));
const samples = modulate(encodePacket('Привет, Android!', { from: 'BASE', to: 'FIELD', id: 17 }), { rate: 48000, offset: 80, delay: 2 });
const wav = Buffer.alloc(44 + samples.length * 2);
wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
wav.writeUInt32LE(48000, 24); wav.writeUInt32LE(96000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
wav.write('data', 36); wav.writeUInt32LE(samples.length * 2, 40);
for (let i = 0; i < samples.length; i++) wav.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(samples[i] * 32767))), 44 + i * 2);
const fixture = join(temp, 'input.wav'); await writeFile(fixture, wav);
const server = spawn(process.execPath, ['tools/serve.mjs', '--port', '0'], { stdio: ['ignore', 'pipe', 'inherit'] });
let browser;
try {
  const [line] = await once(server.stdout, 'data');
  const port = /:(\d+)/.exec(line.toString())[1];
  browser = await chromium.launch({ executablePath: process.env.RB_CHROMIUM || '/usr/bin/chromium', headless: true,
    args: ['--no-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', `--use-file-for-fake-audio-capture=${fixture}`] });
  const context = await browser.newContext({ viewport: { width: 393, height: 852 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${port}/`);
  await page.locator('#diagnostics').evaluate(el => el.open = true);
  await page.locator('#selftest').click();
  await page.waitForFunction(() => document.querySelector('#test-result').textContent.includes('Самопроверка пройдена'));
  console.log('PASS browser worker self-test');
  await page.locator('#from').selectOption('FIELD');
  await page.locator('#listen').click();
  await page.waitForFunction(() => [...document.querySelectorAll('.message.rx p')].some(el => el.textContent === 'Привет, Android!'), { timeout: 20000 });
  await page.locator('#listen').click();
  console.log('PASS fake microphone → AudioWorklet → 48k/8k resampling → Worker → CRC → UTF-8 message');
  await page.locator('#listen').click();
  await page.waitForFunction(() => document.querySelector('#listen').textContent === 'Выключить связь');
  await page.locator('#listen').click();
  console.log('PASS microphone stop/restart');
  await page.locator('#text').fill('OK');
  await page.locator('#send').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Передаю:'));
  await page.locator('#stop-tx').click();
  await page.waitForFunction(() => document.querySelector('.queue-item')?.dataset.state === 'paused');
  assert.equal(await page.locator('.queue-item[data-state=delivered]').count(), 0);
  await page.locator('#listen').click();
  console.log('PASS paused handshake remains durable and is not marked delivered');
  await page.locator('#text').fill('я'.repeat(321));
  assert.equal(await page.locator('#send').isDisabled(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.waitForFunction(() => document.querySelector('#offline-status').textContent.includes('сохранены'));
  await page.screenshot({ path: join(temp, 'android-width.png'), fullPage: true });
  await context.setOffline(true);
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('.message').length >= 1 && document.querySelector('.queue-item')?.dataset.state === 'paused');
  await page.locator('#diagnostics').evaluate(el => el.open = true);
  await page.locator('#selftest').click();
  await page.waitForFunction(() => document.querySelector('#test-result').textContent.includes('Самопроверка пройдена'));
  await page.locator('#listen').click();
  await page.waitForFunction(() => document.querySelector('#listen').textContent === 'Выключить связь');
  await page.locator('#listen').click();
  assert.equal(await page.locator('#from').inputValue(), 'FIELD');
  assert.deepEqual(errors, []);
  console.log('PASS offline reload, cached modules, microphone startup, IndexedDB journal and device settings');
  console.log(`Screenshot: ${join(temp, 'android-width.png')}`);
} finally { await browser?.close(); server.kill('SIGTERM'); }
